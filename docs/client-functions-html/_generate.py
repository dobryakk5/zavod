def simplify_ru_text(text: str) -> str:
    if not text:
        return ""
    result = text.strip()
    replacements = [
        ("Система", "Сервис"),
        ("система", "сервис"),
        ("Позволяет", "Помогает"),
        ("позволяет", "помогает"),
        ("Поддерживается", "Есть"),
        ("поддерживается", "есть"),
        ("Отображается", "Показывается"),
        ("отображается", "показывается"),
        ("Используется", "Нужно для"),
        ("используется", "нужно для"),
        ("Формируется", "Получается"),
        ("формируется", "получается"),
        ("Позволяют", "Помогают"),
        ("позволяют", "помогают"),
    ]
    for src, dst in replacements:
        result = result.replace(src, dst)
    return result


def _has_any(text: str, words: list[str]) -> bool:
    return any(word in text for word in words)


def _has_chatbot_context(text: str, page_slug: str = "") -> bool:
    if _has_any(text, ["чатбот", "чат-бот", "chatbot", "цепоч", "/clients/chatbot"]):
        return True

    # In CRM page these markers are specific to the chatbot chain editor.
    if page_slug == "clients-crm" and _has_any(
        text,
        ["узл", "роут", "валидн", "стартов", "необработанн", "ветвлен", "кнопки"],
    ):
        return True

    # Standalone "бот/бота/боту/ботом" without false positives like "обработан".
    return re.search(r"(^|[^a-zа-яё])бот(а|у|ом)?([^a-zа-яё]|$)", text) is not None


