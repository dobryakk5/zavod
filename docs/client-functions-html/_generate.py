def render_nav(active_slug: str) -> str:
    parts: list[str] = []
    home_cls = "nav-link active" if active_slug == "index" else "nav-link"
    parts.append(f'<a class="{home_cls}" href="{href_for_slug("index")}">{escape(title_for_slug("index"))}</a>')

    parts.append('<div class="nav-section-label">4 сценарных блока</div>')
    for block in NAV_BLOCKS:
        block_slug = block["slug"]
        children = [slug for slug in block.get("children", []) if slug in PAGES_BY_SLUG]
        is_block_active = active_slug == block_slug
        has_active_child = active_slug in children

        group_cls = "nav-link nav-link-group"
        if is_block_active:
            group_cls += " active"
        elif has_active_child:
            group_cls += " active-parent"

        details_attrs = ' class="nav-group" name="nav-blocks"'
        if is_block_active or has_active_child:
            details_attrs += " open"
        parts.append(f"<details{details_attrs}>")
        parts.append('<summary class="nav-group-summary">')
        parts.append('<span class="nav-group-caret" aria-hidden="true"></span>')
        parts.append(f'<a class="{group_cls}" href="{href_for_slug(block_slug)}">{escape(title_for_slug(block_slug))}</a>')
        parts.append("</summary>")
        if children:
            parts.append('<div class="nav-sublist">')
            for child_slug in children:
                child_cls = "nav-link nav-link-sub active" if child_slug == active_slug else "nav-link nav-link-sub"
                parts.append(
                    f'<a class="{child_cls}" href="{href_for_slug(child_slug)}">{escape(title_for_slug(child_slug))}</a>'
                )
            parts.append('</div>')
        parts.append('</details>')

    parts.append('<div class="nav-section-label">Дополнительно</div>')
    route_cls = "nav-link active" if active_slug == "route-reference" else "nav-link"
    parts.append(f'<a class="{route_cls}" href="{href_for_slug("route-reference")}">{escape(title_for_slug("route-reference"))}</a>')
    return "\n".join(parts)


def render_function_card(item: dict[str, str], page_slug: str = "") -> str:
    what_text = simplify_ru_text(item.get("what", ""))
    value_text = simplify_ru_text(item.get("value", ""))
    notes_text = simplify_ru_text(item.get("notes", ""))
    how_text = simplify_ru_text(item.get("how", ""))
    example_text = item.get("example") or build_life_example(item, page_slug)
    lines = [
        '<article class="function-card">',
        f'  <h4>{escape(item.get("name", ""))}</h4>',
        f'  <p><span class="label">Простыми словами:</span> {escape(what_text)}</p>',
    ]
    if value_text:
        lines.append(f'  <p><span class="label">Зачем это нужно:</span> {escape(value_text)}</p>')
    if how_text:
        lines.append(f'  <p><span class="label">Как это сделать:</span> {escape(how_text)}</p>')
    if example_text:
        lines.append(f'  <p class="example-line"><span class="label">Пример из жизни:</span> {escape(example_text)}</p>')
    if notes_text:
        lines.append(f'  <p><span class="label">Комментарий:</span> {escape(notes_text)}</p>')
    lines.append('</article>')
    return "\n".join(lines)


def render_sections(page: dict[str, Any]) -> str:
    parts: list[str] = []
    sections = page.get("sections", [])
    if not sections:
        return ""
    if len(sections) > 1:
        parts.append('<div class="toc-box">')
        parts.append('<div class="toc-title">Быстрый переход по странице</div>')
        parts.append('<div class="toc-links">')
        for idx, s in enumerate(sections, start=1):
            sid = f"sec-{idx}"
            parts.append(f'<a href="#{sid}">{idx}. {escape(s.get("title", ""))}</a>')
        parts.append('</div></div>')
    for idx, s in enumerate(sections, start=1):
        sid = f"sec-{idx}"
        parts.append(f'<section id="{sid}" class="content-section">')
        parts.append(f'  <h2>{idx}. {escape(s.get("title", ""))}</h2>')
        if s.get("intro"):
            parts.append(f'  <p class="section-intro">{escape(s["intro"])}</p>')
        funcs = s.get("functions", [])
        if funcs:
            parts.append('  <div class="function-grid">')
            parts.extend([render_function_card(item, page.get("slug", "")) for item in funcs])
            parts.append('  </div>')
        parts.append('</section>')
    return "\n".join(parts)


def render_ui_paths(page: dict[str, Any]) -> str:
    paths = page.get("ui_paths", [])
    routes = page.get("routes", [])
    if not paths and not routes:
        return ""
    parts = ['<section class="meta-section">', '<h2>Где находится</h2>']
    if paths:
        parts.append('<ul class="plain-list">')
        parts.extend([f'<li>{escape(p)}</li>' for p in paths])
        parts.append('</ul>')
    if routes:
        parts.append('<div class="route-badges">')
        parts.extend([f'<code>{escape(r)}</code>' for r in routes])
        parts.append('</div>')
    parts.append('</section>')
    return "\n".join(parts)


