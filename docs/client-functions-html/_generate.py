def render_scope(page: dict[str, Any]) -> str:
    scope_items = page.get("scope", [])
    if not scope_items:
        return ""
    return (
        '<section class="meta-section scope-box"><h2>Область описания</h2><ul class="plain-list">'
        + "".join(f"<li>{escape(item)}</li>" for item in scope_items)
        + "</ul></section>"
    )


def render_stats_strip(page: dict[str, Any]) -> str:
    total_funcs = sum(
        page_function_count(p)
        for p in PAGES
        if p["slug"] != "route-reference" and not p.get("exclude_from_coverage")
    )
    page_funcs = page_function_count(page)
    page_routes = len(page.get("routes", []))
    cards = [
        ("Страниц в каталоге", str(len(PAGES))),
        ("Функций на странице", str(page_funcs)),
        ("Маршрутов на странице", str(page_routes)),
        ("Оценка общего покрытия", f"{total_funcs} функций"),
    ]
    html_cards = "".join(
        f'<div class="stat-card"><span class="stat-value">{escape(v)}</span><span class="stat-label">{escape(k)}</span></div>'
        for k, v in cards
    )
    return f'<section class="stats-strip">{html_cards}</section>'


