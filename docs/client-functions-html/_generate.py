def scan_routes() -> list[dict[str, str]]:
    base = PROJECT_ROOT / "frontend" / "app"
    results: list[dict[str, str]] = []
    if not base.exists():
        return results
    for file in sorted(base.rglob("page.tsx")):
        rel = file.relative_to(base)
        parts = list(rel.parts)
        if not parts:
            continue
        if parts == ["page.tsx"]:
            route = "/"
        else:
            route_parts = parts[:-1]
            route = "/" + "/".join(route_parts)
        results.append({"route": route, "file": str(file.relative_to(PROJECT_ROOT))})
    return results


